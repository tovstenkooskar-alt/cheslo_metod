import math

def relative_error(approx, exact):
    dx = abs(exact - approx)
    return dx / abs(exact)

print("1. Пи и 3.14")
approx1 = 3.14
exact1 = math.pi
print("Абсолютная ошибка:", abs(exact1 - approx1))
print("Относительная ошибка:", relative_error(approx1, exact1))
print()

print("2. (0.1 + 0.2) и 0.3")
approx2 = 0.1 + 0.2
exact2 = 0.3
print("Абсолютная ошибка:", abs(exact2 - approx2))
print("Относительная ошибка:", relative_error(approx2, exact2))
print()

print("3. Сумма миллиона 0.1")
arr = []
for i in range(1000000):
    arr.append(0.1)

approx3 = sum(arr)
exact3 = math.fsum(arr)
print("Абсолютная ошибка:", abs(exact3 - approx3))
print("Относительная ошибка:", relative_error(approx3, exact3))
print()

print("ВЫВОД")
print("1. Для Пи (3.14) обе ошибки относительно малы, так как это небольшое округление.")
print("2. Для (0.1 + 0.2) абсолютная ошибка мала из-за особенностей работы чисел в памяти, но она не равна нулю. Относительная тоже очень мала.")
print("3. Для суммы миллиона 0.1 абсолютная погрешность сильно возрастает из-за того, что ошибка накапливается при каждом сложении в цикле. При этом относительная погрешность остается маленькой, так как итоговая сумма (100000) большая.")
print("Итог: абсолютная ошибка может быть большой, но на фоне огромного числа она теряется (поэтому относительная - мала), и наоборот.")